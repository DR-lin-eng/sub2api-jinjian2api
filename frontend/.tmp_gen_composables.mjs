/**
 * Auto-generates one thin orchestrator composable per feature.
 * Composable wraps Query + Action stores into a flat interface.
 * Per spec §5.5 R6 + §5.6 R7.
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dir = dirname(fileURLToPath(import.meta.url))
const featuresDir = join(__dir, 'src/features')
const AUTO_GEN_HEADER = '/* Auto-generated by .tmp_gen_composables.mjs */'

let count = 0

for (const feature of readdirSync(featuresDir)) {
  const featDir = join(featuresDir, feature)
  const storesDir = join(featDir, 'presentation/stores')
  const composablesDir = join(featDir, 'presentation/composables')
  if (!existsSync(storesDir)) continue

  const storeFiles = readdirSync(storesDir).filter(f => f.endsWith('Store.ts'))
  if (storeFiles.length === 0) continue

  const pascal = s => s.replace(/(^|[-_])([a-z])/g, (_, __, c) => c.toUpperCase())
  const featPascal = pascal(feature)
  const composableName = `use${featPascal}`
  const composableFile = join(composablesDir, `${composableName}.ts`)

  // Skip if file exists and was NOT auto-generated (hand-written file)
  if (existsSync(composableFile)) {
    const existing = readFileSync(composableFile, 'utf8')
    if (!existing.startsWith(AUTO_GEN_HEADER)) continue
  }

  // Collect all store imports
  const queryStores = storeFiles.filter(f => f.includes('QueryStore'))
  const actionStores = storeFiles.filter(f => f.includes('ActionStore'))

  const imports = []
  const storeVars = []

  for (const sf of queryStores) {
    const storeName = sf.replace(/\.ts$/, '')
    const useFn = `use${storeName[0].toUpperCase()}${storeName.slice(1)}`
    imports.push(`import { ${useFn} } from '@/features/${feature}/presentation/stores/${storeName}'`)
    storeVars.push({ varName: `q_${storeName}`, useFn, type: 'query' })
  }
  for (const sf of actionStores) {
    const storeName = sf.replace(/\.ts$/, '')
    const useFn = `use${storeName[0].toUpperCase()}${storeName.slice(1)}`
    imports.push(`import { ${useFn} } from '@/features/${feature}/presentation/stores/${storeName}'`)
    storeVars.push({ varName: `a_${storeName}`, useFn, type: 'action' })
  }

  const storeSetup = storeVars.map(s => `  const ${s.varName} = ${s.useFn}()`).join('\n')
  const returnEntries = storeVars.map(s => `    ...${s.varName}`).join(',\n')

  const code = `${AUTO_GEN_HEADER}
/**
 * ${composableName} — thin orchestrator composable for ${featPascal}.
 * Re-exports all Query + Action store state and methods as a flat interface.
 * Per spec §5.5 R6: composable coordinates stores + lifecycle.
 * See usePromptAudit.ts for the hand-crafted reference implementation with
 * full i18n error mapping and UI-local state — this composable is the
 * minimal scaffold for features that do not yet have hand-crafted logic.
 */

${imports.join('\n')}

export function ${composableName}() {
${storeSetup}
  return {
${returnEntries},
  }
}
`

  if (!existsSync(composablesDir)) mkdirSync(composablesDir, { recursive: true })
  writeFileSync(composableFile, code)
  count++
}

console.log(`Generated ${count} composable files.`)
